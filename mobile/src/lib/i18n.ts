export const TRANSLATIONS: Record<Language, TranslationDictionary> = { en: EN, tr: TR };

/** Narrows an arbitrary string to a supported language, or null. */
export function parseLanguage(value: string | null | undefined): Language | null {
  if (!value) return null;
  const normalised = value.toLowerCase().split('-')[0];
  return LANGUAGES.includes(normalised as Language) ? (normalised as Language) : null;
}
